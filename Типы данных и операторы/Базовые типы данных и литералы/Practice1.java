
public static void main(String[] args) {
    byte a = 3, b = 0;
    short c = 32700, d = 0;
    int e = -2147483647, f = 0;
    long g = 9223, h = 0;
    float i = 8.5f, j = 0.0f;
    double k = 36.6, l = 0.0;
    char m = 'a', o = 0;
    boolean p = true, s = false;

    System.out.println("byte a = " + a + ", byte b = " + b);
    System.out.println("short c = " + c + ", short d = " + d);
    System.out.println("int e = " + e + ", int f = " + f);
    System.out.println("long g = " + g + ", long h = " + h);
    System.out.println("float i = " + i + ", float j = " + j);
    System.out.println("double k = " + k + ", double l = " + l);
    System.out.println("char m = " + m + ", char o = " + o);
    System.out.println("boolean p = " + p + ", boolean s = " + s);
}